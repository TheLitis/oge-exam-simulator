'use strict';
const path = require('node:path');
const APPLICATION = 'oge-exam-simulator';
const TITLE = 'Симулятор экзамена ОГЭ';

function stringValue(value) {
  value = String(value);
  if (/[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]/.test(value)) throw new Error('Недопустимый символ в ярлыке приложения.');
  return value.replace(/\\/g, '\\\\').replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t');
}

// Values and Exec arguments have separate escaping layers. The caller adds
// intended field codes such as %k outside the argument generated here.
function execArgument(value) {
  const argument = String(value).replace(/%/g, '%%').replace(/[\\"$`]/g, character => '\\' + character);
  return '"' + stringValue(argument) + '"';
}

function desktopEntry(root) {
  // Keep the executable fixed: even '=' in the home path is a plain argument.
  // start.sh clears Node's environment and runs the bundled runtime.
  return `[Desktop Entry]\nVersion=1.0\nType=Application\nName=${TITLE}\nExec=/bin/sh ${execArgument(path.join(root, 'start.sh'))}\nIcon=${stringValue(path.join(root, 'app/ui/icon.svg'))}\nTerminal=false\nCategories=Education;\nStartupNotify=false\nX-OGE-Application=${APPLICATION}\n`;
}

function isApplicationShortcut(contents) {
  if (contents.split(/\r?\n/).includes('X-OGE-Application=' + APPLICATION)) return true;
  // Migrate the launcher generated by the original distribution as well.
  return /^Type=Application$/m.test(contents) && contents.split(/\r?\n/).includes('Name=' + TITLE)
    && /^Exec=.*[/\\]start\.sh(?:"|\s|$)/m.test(contents);
}

module.exports = { APPLICATION, TITLE, stringValue, execArgument, desktopEntry, isApplicationShortcut };
